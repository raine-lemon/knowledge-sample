def fm(**kw):
    lines = ["---"]
    for k, v in kw.items():
        if isinstance(v, list):
            lines.append("%s:" % k)
            lines += ['  - "%s"' % x for x in v]
        else:
            lines.append('%s: %s' % (k, v))
    lines.append("---")
    return "\n".join(lines)

