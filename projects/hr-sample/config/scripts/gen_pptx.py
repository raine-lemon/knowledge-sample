import data as D

OUT = os.path.expanduser("~/Documents/hr-samples/")
FONT = "맑은 고딕"

def deck(path, title, subtitle, slides):
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    BLANK = prs.slide_layouts[6]
    s = prs.slides.add_slide(BLANK)
    tb = s.shapes.add_textbox(Inches(1.0), Inches(2.6), Inches(11.3), Inches(2.4))
    tf = tb.text_frame
    p = tf.paragraphs[0]; p.text = title
    p.font.size, p.font.bold, p.font.name = Pt(44), True, FONT
    for t, sz, c in [(subtitle, 16, 0x66), (D.FIXTURE_NOTE, 12, 0x99)]:
        q = tf.add_paragraph(); q.text = t
        q.font.size, q.font.name = Pt(sz), FONT
        q.font.color.rgb = RGBColor(c, c, c); q.space_before = Pt(14)
    for head, sub, bullets in slides:
        sl = prs.slides.add_slide(BLANK)
        tb = sl.shapes.add_textbox(Inches(0.8), Inches(0.6), Inches(11.7), Inches(1.0))
        p = tb.text_frame.paragraphs[0]; p.text = head
        p.font.size, p.font.bold, p.font.name = Pt(30), True, FONT
        top = 1.7
        if sub:
            sb = sl.shapes.add_textbox(Inches(0.8), Inches(1.55), Inches(11.7), Inches(0.5))
            sp = sb.text_frame.paragraphs[0]; sp.text = sub
            sp.font.size, sp.font.name = Pt(13), FONT
            sp.font.color.rgb = RGBColor(0x77,0x77,0x77); top = 2.25
        body = sl.shapes.add_textbox(Inches(0.9), Inches(top), Inches(11.5), Inches(4.8))
        tf = body.text_frame; tf.word_wrap = True
        for i, (lvl, txt) in enumerate(bullets):
            par = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            par.text = ("• " if lvl == 0 else "– ") + txt
            par.level = lvl
            par.font.size = Pt(16 if lvl == 0 else 13)
            par.font.name = FONT
            par.font.color.rgb = RGBColor(0x22,0x22,0x22) if lvl==0 else RGBColor(0x55,0x55,0x55)
            par.space_after = Pt(9 if lvl == 0 else 5)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    prs.save(path)
    return os.path.getsize(path), len(slides) + 1


